#!/bin/sh
set -eu

# Applies Voidline's generated palette to regular desktop applications. GTK
# loads gtk.css only when an application starts, while the standard GNOME
# appearance keys and Settings portal notify already-running applications that
# support live color-scheme changes.

valid_color() {
    printf '%s\n' "$1" | grep -Eq '^#[0-9A-Fa-f]{6}$'
}

valid_name() {
    case "$1" in
        ""|*[!A-Za-z0-9\ ._+-]*) return 1 ;;
        *) return 0 ;;
    esac
}

ensure_import() {
    css_file=$1
    directory=$(dirname "$css_file")
    mkdir -p "$directory"
    import='@import url("voidline.css");'

    if [ ! -f "$css_file" ]; then
        printf '%s\n' "$import" >"$css_file"
        return
    fi
    grep -Fqx "$import" "$css_file" && return

    temporary=$(mktemp "$directory/.gtk-css.XXXXXX")
    {
        printf '%s\n\n' "$import"
        cat "$css_file"
    } >"$temporary"
    chmod --reference="$css_file" "$temporary" 2>/dev/null || chmod 600 "$temporary"
    mv -f "$temporary" "$css_file"
}

update_settings_ini() {
    ini_file=$1
    ini_theme=$2
    ini_dark=$3
    ini_font=$4
    ini_icons=$5
    ini_cursor=$6
    directory=$(dirname "$ini_file")
    mkdir -p "$directory"
    temporary=$(mktemp "$directory/.gtk-settings.XXXXXX")

    if [ -f "$ini_file" ]; then
        source_file=$ini_file
    else
        source_file=/dev/null
    fi

    awk \
        -v theme="$ini_theme" \
        -v dark="$ini_dark" \
        -v font="$ini_font 11" \
        -v icons="$ini_icons" \
        -v cursor="$ini_cursor" '
        function emit_missing() {
            if (!seen_theme) print "gtk-theme-name=" theme
            if (!seen_dark && dark != "omit")
                print "gtk-application-prefer-dark-theme=" dark
            if (!seen_font) print "gtk-font-name=" font
            if (!seen_icons) print "gtk-icon-theme-name=" icons
            if (!seen_cursor) print "gtk-cursor-theme-name=" cursor
        }
        BEGIN { in_settings = 0; found_settings = 0 }
        /^\[Settings\][[:space:]]*$/ {
            if (in_settings) emit_missing()
            print
            in_settings = 1
            found_settings = 1
            next
        }
        /^\[/ {
            if (in_settings) {
                emit_missing()
                in_settings = 0
            }
            print
            next
        }
        in_settings {
            key = $0
            sub(/[[:space:]]*=.*$/, "", key)
            gsub(/[[:space:]]/, "", key)
            if (key == "gtk-theme-name") {
                print "gtk-theme-name=" theme
                seen_theme = 1
                next
            }
            if (key == "gtk-application-prefer-dark-theme") {
                if (dark != "omit")
                    print "gtk-application-prefer-dark-theme=" dark
                seen_dark = 1
                next
            }
            if (key == "gtk-font-name") {
                print "gtk-font-name=" font
                seen_font = 1
                next
            }
            if (key == "gtk-icon-theme-name") {
                print "gtk-icon-theme-name=" icons
                seen_icons = 1
                next
            }
            if (key == "gtk-cursor-theme-name") {
                print "gtk-cursor-theme-name=" cursor
                seen_cursor = 1
                next
            }
            print
            next
        }
        { print }
        END {
            if (in_settings) {
                emit_missing()
            } else if (!found_settings) {
                if (NR > 0) print ""
                print "[Settings]"
                emit_missing()
            }
        }
    ' "$source_file" >"$temporary"

    if [ -f "$ini_file" ]; then
        chmod --reference="$ini_file" "$temporary" 2>/dev/null || chmod 600 "$temporary"
    else
        chmod 600 "$temporary"
    fi
    mv -f "$temporary" "$ini_file"
}

set_gsetting() {
    schema=$1
    key=$2
    value=$3
    command -v gsettings >/dev/null 2>&1 || return 0
    gsettings writable "$schema" "$key" 2>/dev/null |
        grep -qx true || return 0
    gsettings set "$schema" "$key" "$value"
}

